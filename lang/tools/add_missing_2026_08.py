def load(loc: str) -> dict:
    return json.loads((LANG / f"{loc}.json").read_text(encoding="utf-8"))


def save(loc: str, data: dict) -> None:
    ordered = dict(sorted(data.items(), key=lambda kv: kv[0].lower()))
    (LANG / f"{loc}.json").write_text(
        json.dumps(ordered, ensure_ascii=False, indent=4) + "\n",
        encoding="utf-8",
    )


def merge(data: dict, adds: dict[str, str], *, overwrite_identity: bool = True) -> int:
    n = 0
    for k, v in adds.items():
        if k not in data:
            data[k] = v
            n += 1
        elif overwrite_identity and data[k] == k and v != k:
            data[k] = v
            n += 1
    return n


